/**
 * Locale values that are deliberately IDENTICAL to their `en` value.
 *
 * `untranslated-values.test.ts` fails on any non-`en` leaf that equals the `en`
 * leaf, because that is how an untranslated string looks once someone copied the
 * English file to seed a new locale (spec 2026-09-26-01: the French 2FA login
 * step, passkey button included, shipped in English that way). This file lists
 * the exceptions, one `"<namespace>:<key.path>"` entry per string, with the
 * locales for which the identical value is correct.
 *
 * Rules for adding an entry:
 * - Only for a value that is right as-is in that locale: a brand, product or
 *   protocol name, a sample value, a technical term the locale's own help texts
 *   use untranslated, or a word spelled the same in that language.
 * - Never to silence the test for a string nobody got round to translating.
 *   Translate it instead.
 * - Name the locales one by one. There is no namespace or wildcard exclusion.
 *
 * Values with no letters outside `{{placeholders}}` ("—", "#", "09:00",
 * "{{from}} → {{to}}") have nothing to translate and are skipped by the test,
 * so they need no entry. An entry that no longer matches (the value got
 * translated, or the key is gone) fails the test too, so this list cannot rot.
 *
 * The trailing comment on each line is the English value, for review.
 */

