import * as React from "react";

import { cn } from "@/lib/utils";

const Card = React.forwardRef<
  HTMLDivElement,
  React.HTMLAttributes<HTMLDivElement>
>(({ className, ...props }, ref) => (
  <div
    ref={ref}
    className={cn(
      // Dark mode gets its elevation from light, not shadow: a slightly
      // lighter border plus a faint top-lit gradient over bg-card.
      // --card-pad is the header/content/footer padding: 16px on a phone,
      // 24px from sm. A variable, so a caller's p-0 / pt-6 still overrides
      // the part's padding through cn().
      "rounded-xl border bg-card text-card-foreground shadow-card [--card-pad:1rem] sm:[--card-pad:1.5rem] dark:border-white/10 dark:bg-gradient-to-b dark:from-white/[0.04] dark:to-transparent dark:shadow-[inset_0_1px_0_0_rgba(255,255,255,0.06)]",
      className
    )}
    {...props}
  />
));
Card.displayName = "Card";

