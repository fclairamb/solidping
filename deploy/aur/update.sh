#!/usr/bin/env bash
# Renders solidping-bin/PKGBUILD and solidping-bin/.SRCINFO for a release.
#
#   deploy/aur/update.sh <version> [checksums-file] [pkgrel]
#
# <version> is the release without its "v" (0.52.0). The checksums come from
# the release's solidping-checksums.txt (downloaded with gh when no file is
# given). pkgrel defaults to 1; bump it to republish the same version with a
# packaging fix. .SRCINFO is written here rather than with
# `makepkg --printsrcinfo` so this runs on any host; deploy/aur/test.sh checks
# both stay equal.
set -euo pipefail

version="${1:?usage: update.sh <version> [checksums-file] [pkgrel]}"
checksums="${2:-}"
pkgrel="${3:-1}"
here="$(cd "$(dirname "$0")" && pwd)"
pkg="$here/solidping-bin"

if ! [[ "$version" =~ ^[0-9]+\.[0-9]+\.[0-9]+$ ]]; then
  echo "update.sh: version must be X.Y.Z without a leading v (got '$version')" >&2
  exit 1
fi

if [[ -z "$checksums" ]]; then
  tmp="$(mktemp -d)"
  trap 'rm -rf "$tmp"' EXIT
  gh release download "v$version" --repo fclairamb/solidping -p solidping-checksums.txt -D "$tmp"
  checksums="$tmp/solidping-checksums.txt"
fi

# Release asset name of each Arch architecture, as server-release publishes
# them (.github/workflows/ci.yml, "Build the server for every published platform").
declare -A asset=(
  [x86_64]=solidping-linux-amd64.gz
  [aarch64]=solidping-linux-arm64.gz
  [riscv64]=solidping-linux-riscv64.gz
)
arches=(x86_64 aarch64 riscv64)

declare -A sum
for arch in "${arches[@]}"; do
  sum[$arch]="$(awk -v f="${asset[$arch]}" '$2 == f || $2 == "*" f { print $1 }' "$checksums")"
  if ! [[ "${sum[$arch]}" =~ ^[0-9a-f]{64}$ ]]; then
    echo "update.sh: no sha256 for ${asset[$arch]} in $checksums" >&2
    exit 1
  fi
done

sha() { sha256sum "$1" | cut -d' ' -f1; }
service_sum="$(sha "$pkg/solidping.service")"
sysusers_sum="$(sha "$pkg/solidping.sysusers")"

url=https://github.com/fclairamb/solidping
desc='Distributed, self-hostable uptime monitoring (prebuilt binary)'

{
  cat <<PKG
# Maintainer: Florent Clairambault <florent dot clairambault at gmail dot com>
# Generated by deploy/aur/update.sh in ${url}: edit the template there.
pkgname=solidping-bin
pkgver=${version}
pkgrel=${pkgrel}
pkgdesc='${desc}'
arch=('x86_64' 'aarch64' 'riscv64')
url='${url}'
license=('AGPL-3.0-only')
provides=('solidping')
conflicts=('solidping')
install=solidping-bin.install
# A static Go binary built with -s -w: nothing to strip, no debug symbols.
options=('!strip' '!debug')
source=('solidping.service' 'solidping.sysusers')
sha256sums=('${service_sum}'
            '${sysusers_sum}')
PKG
  for arch in "${arches[@]}"; do
    # shellcheck disable=SC2016 # ${pkgver} and ${url} are for makepkg to expand
    printf 'source_%s=("solidping-${pkgver}-%s.gz::${url}/releases/download/v${pkgver}/%s")\n' "$arch" "$arch" "${asset[$arch]}"
  done
  for arch in "${arches[@]}"; do
    printf "sha256sums_%s=('%s')\n" "$arch" "${sum[$arch]}"
  done
  cat <<'PKG'

package() {
  # makepkg decompresses solidping-<ver>-<arch>.gz into solidping-<ver>-<arch>.
  install -Dm755 "solidping-${pkgver}-${CARCH}" "${pkgdir}/usr/bin/solidping"
  install -Dm644 solidping.service "${pkgdir}/usr/lib/systemd/system/solidping.service"
  install -Dm644 solidping.sysusers "${pkgdir}/usr/lib/sysusers.d/solidping.conf"
}
PKG
} >"$pkg/PKGBUILD"

{
  printf 'pkgbase = solidping-bin\n'
  printf '\tpkgdesc = %s\n' "$desc"
  printf '\tpkgver = %s\n' "$version"
  printf '\tpkgrel = %s\n' "$pkgrel"
  printf '\turl = %s\n' "$url"
  printf '\tinstall = solidping-bin.install\n'
  for arch in "${arches[@]}"; do printf '\tarch = %s\n' "$arch"; done
  printf '\tlicense = AGPL-3.0-only\n'
  printf '\tprovides = solidping\n'
  printf '\tconflicts = solidping\n'
  printf '\toptions = !strip\n\toptions = !debug\n'
  printf '\tsource = solidping.service\n\tsource = solidping.sysusers\n'
  printf '\tsha256sums = %s\n\tsha256sums = %s\n' "$service_sum" "$sysusers_sum"
  for arch in "${arches[@]}"; do
    printf '\tsource_%s = solidping-%s-%s.gz::%s/releases/download/v%s/%s\n' "$arch" "$version" "$arch" "$url" "$version" "${asset[$arch]}"
    printf '\tsha256sums_%s = %s\n' "$arch" "${sum[$arch]}"
  done
  printf '\npkgname = solidping-bin\n'
} >"$pkg/.SRCINFO"

echo "rendered solidping-bin $version-$pkgrel"
