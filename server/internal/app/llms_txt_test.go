// TestServeRootLLMsTxtMissingFile404s asserts a missing root docs file 404s
// (via the docs 404 page) rather than falling through to the SPA shell.
func TestServeRootLLMsTxtMissingFile404s(t *testing.T) {
	t.Parallel()
	r := require.New(t)

	s := &Server{}

	w := httptest.NewRecorder()
	s.serveDocsFile(w, "/llms-does-not-exist.txt")

	resp := w.Result()
	defer func() { _ = resp.Body.Close() }()

	r.Equal(http.StatusNotFound, resp.StatusCode)
}
